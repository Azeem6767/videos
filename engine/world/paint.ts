/** Deck top, transverse boards. 2048 px = 2 m x 2 m (1024 texels/m). 8 boards of 0.25 m = 256 px.
 *  Gaps ~4 % of the pitch (8 px core + soft rim), sunlit lip + shaded lip, nails + rare knots. */
